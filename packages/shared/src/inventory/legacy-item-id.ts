const TITLE_HINTS: Array<[RegExp, number]> = [
  [/mystic\s*sword|tier\s*(i{1,3}|[123])\s*sword|legendary.*sword/i, 283],
  [/mystic\s*bow|tier\s*(i{1,3}|[123])\s*bow/i, 261],
  [/rage\s*pants|dark\s*pants|mystic\s*pants|fresh\s*pants|leggings/i, 300],
  [/chunk\s*of\s*vile|\bvile\b/i, 263],
  [/totally\s*legit|\bgem\b/i, 388],
  [/funky\s*feather/i, 288],
  [/repair\s*kit/i, 359],
  [/\bbow\b/i, 261],
  [/\bsword\b/i, 283],
  [/\barr(?:ow|ows)\b/i, 262],
  [/\bobsidian\b/i, 49],
];

export function resolveLegacyItemId(input: {
  id?: string | number | null;
  title?: string | null;
}): number {
  const raw = input.id;
  if (typeof raw === "number" && Number.isFinite(raw) && raw > 0) {
    return Math.trunc(raw);
  }
  if (typeof raw === "string") {
    const trimmed = raw.trim();
    if (/^\d+$/.test(trimmed)) return Number(trimmed);
    const key = trimmed.replace(/^minecraft:/i, "").toLowerCase();
    if (NAME_TO_LEGACY[key] !== undefined) return NAME_TO_LEGACY[key]!;
  }

  const title = input.title ?? "";
  for (const [re, id] of TITLE_HINTS) {
    if (re.test(title)) return id;
  }
  return 0;
}

export function normalizeItemMeta(meta: unknown): string | number {
  if (typeof meta === "number" && Number.isFinite(meta)) return Math.trunc(meta);
  if (typeof meta === "string" && meta.trim()) {
    const trimmed = meta.trim().replace(/^#/, "");
    if (/^\d+$/.test(trimmed)) return Number(trimmed);
    return trimmed.toUpperCase();
  }
  return 0;
}
